import { randomUUID } from 'node:crypto';

export async function createCampusOperations(db, iceServers, approvedStudent) {
    await db.exec(`
        CREATE TABLE IF NOT EXISTS listings (
            id TEXT PRIMARY KEY, kind TEXT, title TEXT, details TEXT, date TEXT, url TEXT
        );
        CREATE TABLE IF NOT EXISTS hidden_posts (id TEXT PRIMARY KEY);
        CREATE TABLE IF NOT EXISTS moderation_log (
            id ${db.postgres ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : 'INTEGER'} PRIMARY KEY, moderator TEXT, target TEXT, action TEXT, created BIGINT
        );
    `);
    const broadcasts = new Map();
    const invalid = { status: 400, error: 'Check the information and try again.' };
    const missing = { status: 404, error: 'This item is unavailable.' };
    const forbidden = { status: 403, error: 'Moderator or broadcast owner access is required.' };
    const ok = { data: { ok: true } };

    return async function operations(method, path, params, member, input) {
        const now = Date.now();
        const owner = member.id;
        const moderator = member.moderator;
        if (method === 'GET' && path === '/api/listings') {
            return { data: await db.prepare("SELECT * FROM listings WHERE date = '' OR date >= ? ORDER BY (date = ''), date, title").all(new Date(now + 3600000).toISOString().slice(0, 10)) };
        }
        if (method === 'GET' && path === '/api/leaderboard') {
            const counts = new Map();
            for (const row of await db.prepare('SELECT group_name, email FROM memberships JOIN accounts ON accounts.id = memberships.owner').all()) {
                if (approvedStudent(row.email)) counts.set(row.group_name, (counts.get(row.group_name) || 0) + 1);
            }
            return { data: [...counts].map(([name, members]) => ({ name, members }))
                .sort((a, b) => b.members - a.members || a.name.localeCompare(b.name)) };
        }
        if (path.startsWith('/api/moderation')) {
            if (!moderator) return forbidden;
            if (method === 'GET' && path === '/api/moderation/users') {
                const offset = Number(params.get('offset') ?? 0);
                if (!Number.isSafeInteger(offset) || offset < 0 || offset > 10_000_000) return invalid;
                const accounts = await db.prepare(`SELECT accounts.id, accounts.email, profiles.name, profiles.username,
                    disabled_accounts.id IS NOT NULL AS disabled FROM accounts
                    LEFT JOIN profiles USING (id) LEFT JOIN disabled_accounts USING (id)
                    ORDER BY accounts.email LIMIT 51 OFFSET ?`).all(offset);
                return { data: { accounts: accounts.slice(0, 50), hasMore: accounts.length > 50, ownId: owner } };
            }
            if (method === 'GET' && path === '/api/moderation') {
                return { data: {
                    listings: await db.prepare('SELECT * FROM listings ORDER BY date, title').all(),
                    reports: await db.prepare(`SELECT posts.id, posts.body, CAST(count(*) AS INTEGER) AS reports, hidden_posts.id IS NOT NULL AS hidden
                        FROM reports JOIN posts ON posts.id = reports.post LEFT JOIN hidden_posts ON hidden_posts.id = posts.id
                        GROUP BY posts.id, posts.body, hidden_posts.id ORDER BY max(reports.created) DESC LIMIT 100`).all()
                } };
            }
            if (method !== 'POST') return missing;
            if (path === '/api/moderation/users') {
                if (typeof input?.id !== 'string' || typeof input.disabled !== 'boolean' || input.id === owner) return invalid;
                return db.transaction(async () => {
                    const account = await db.prepare('SELECT email FROM accounts WHERE id = ?' + (db.postgres ? ' FOR UPDATE' : '')).get(input.id);
                    if (!account) return missing;
                    if (input.disabled) {
                        await db.prepare('INSERT INTO disabled_accounts VALUES (?) ON CONFLICT DO NOTHING').run(input.id);
                        await db.prepare('DELETE FROM sessions WHERE email = ?').run(account.email);
                        await db.prepare('DELETE FROM challenges WHERE email = ?').run(account.email);
                    } else {
                        await db.prepare('DELETE FROM disabled_accounts WHERE id = ?').run(input.id);
                    }
                    await db.prepare('INSERT INTO moderation_log(moderator, target, action, created) VALUES (?, ?, ?, ?)').run(owner, input.id, input.disabled ? 'disable-account' : 'enable-account', now);
                    return ok;
                });
            }
            if (path === '/api/moderation/listings') {
                if (!['event', 'opportunity'].includes(input?.kind) || typeof input.title !== 'string' ||
                    !input.title.trim() || input.title.length > 120 || typeof input.details !== 'string' ||
                    input.details.length > 1000 || typeof input.date !== 'string' || typeof input.url !== 'string') return invalid;
                const parsedDate = new Date(input.date);
                if ((input.kind === 'event' || input.date) && (!/^\d{4}-\d{2}-\d{2}$/.test(input.date) ||
                    !Number.isFinite(+parsedDate) || parsedDate.toISOString().slice(0, 10) !== input.date)) return invalid;
                if (input.url) {
                    try { if (new URL(input.url).protocol !== 'https:') return invalid; }
                    catch { return invalid; }
                }
                if (input.id && typeof input.id !== "string") return invalid;
                if (input.id && !await db.prepare('SELECT 1 FROM listings WHERE id = ?').get(input.id)) return missing;
                await db.prepare('INSERT INTO listings VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT(id) DO UPDATE SET kind=excluded.kind, title=excluded.title, details=excluded.details, date=excluded.date, url=excluded.url').run(input.id || randomUUID(), input.kind, input.title.trim(), input.details.trim(), input.date, input.url);
                return ok;
            }
            if (path === '/api/moderation/remove-listing' && typeof input?.id === 'string') {
                await db.prepare('DELETE FROM listings WHERE id = ?').run(input.id);
                return ok;
            }
            if (path === '/api/moderation/reports' && ['hide', 'restore', 'dismiss'].includes(input?.action) && typeof input.id === 'string') {
                return db.transaction(async () => {
                    const post = await db.prepare('SELECT id FROM posts WHERE id = ?' + (db.postgres ? ' FOR UPDATE' : '')).get(input.id);
                    if (!post || !await db.prepare('SELECT 1 FROM reports WHERE post = ?').get(input.id)) return missing;
                    if (input.action === 'hide') await db.prepare('INSERT INTO hidden_posts VALUES (?) ON CONFLICT DO NOTHING').run(input.id);
                    else if (input.action === 'restore') await db.prepare('DELETE FROM hidden_posts WHERE id = ?').run(input.id);
                    else await db.prepare('DELETE FROM reports WHERE post = ? AND NOT EXISTS (SELECT 1 FROM hidden_posts WHERE id = ?)').run(input.id, input.id);
                    await db.prepare('INSERT INTO moderation_log(moderator, target, action, created) VALUES (?, ?, ?, ?)').run(owner, input.id, input.action, now);
                    return ok;
                });
            }
            return missing;
        }
        if (path !== '/api/broadcast') return undefined;
        for (const [id, room] of broadcasts) {
            if (room.expires <= now) broadcasts.delete(id);
            else for (const [viewer, peer] of room.viewers) {
                if (peer.expires <= now) room.viewers.delete(viewer);
            }
        }
        if (method === 'GET') return { data: {
            rooms: [...broadcasts].map(([id, room]) => ({ id, title: room.title, own: room.owner === owner })),
            iceServers
        } };
        if (method !== 'POST') return missing;
        if (input?.action === 'start') {
            if (typeof input.title !== 'string' || !input.title.trim() || input.title.length > 120) return invalid;
            const existing = [...broadcasts].find(([, room]) => room.owner === owner);
            if (existing) return { data: { id: existing[0], iceServers } };
            if (broadcasts.size >= 20) return { status: 429, error: 'All broadcast slots are in use.' };
            const id = randomUUID();
            broadcasts.set(id, { owner, title: input.title.trim(), expires: now + 30000, viewers: new Map() });
            return { data: { id, iceServers } };
        }
        const room = broadcasts.get(input?.id);
        if (!room) return missing;
        const host = room.owner === owner;
        const validSdp = typeof input.sdp === 'string' && input.sdp.length <= 16000 && input.sdp.startsWith('v=0');
        if (input.action === 'poll' && host) {
            room.expires = now + 30000;
            return { data: [...room.viewers].map(([id, peer]) => ({ id, offer: peer.offer, answered: Boolean(peer.answer) })) };
        }
        if (input.action === 'end' && (host || moderator)) { broadcasts.delete(input.id); return ok; }
        if (input.action === 'offer' && !host && validSdp) {
            if (!room.viewers.has(owner) && room.viewers.size >= 6) return { status: 429, error: 'This broadcast has reached six viewers.' };
            room.viewers.set(owner, { offer: input.sdp, expires: now + 30000 });
            return ok;
        }
        if (input.action === 'answer' && host && validSdp) {
            const peer = room.viewers.get(input.viewer);
            if (peer && peer.offer === input.offer) peer.answer = input.sdp;
            return ok;
        }
        const peer = room.viewers.get(owner);
        if (input.action === 'poll' && peer) {
            peer.expires = now + 30000;
            return { data: { answer: peer.answer || null } };
        }
        if (input.action === 'leave') { room.viewers.delete(owner); return ok; }
        return forbidden;
    };
}
