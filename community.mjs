import { randomUUID } from 'node:crypto';

const groups = new Set(['NACOS', 'Press Club', 'Law Society', 'GDSC']);
const mediaTypes = new Set(['image/jpeg', 'image/png', 'image/gif', 'image/webp', 'video/mp4', 'video/webm']);
const mediaSignatures = {
    'image/jpeg': data => data.subarray(0, 3).toString('hex') === 'ffd8ff',
    'image/png': data => data.subarray(0, 8).toString('hex') === '89504e470d0a1a0a',
    'image/gif': data => ['GIF87a', 'GIF89a'].includes(data.toString('ascii', 0, 6)),
    'image/webp': data => data.toString('ascii', 0, 4) === 'RIFF' && data.toString('ascii', 8, 12) === 'WEBP',
    'video/mp4': data => data.toString('ascii', 4, 8) === 'ftyp',
    'video/webm': data => data.subarray(0, 4).toString('hex') === '1a45dfa3'
};
const text = (value, max) => typeof value === 'string' && value.trim().length <= max ? value.trim() : '';
const invalid = { status: 400, error: 'Check the information and try again.' };
const missing = { status: 404, error: 'This item is unavailable.' };

export async function createCommunity(db, approvedStudent) {
    await db.exec(`
        CREATE TABLE IF NOT EXISTS profiles (id TEXT PRIMARY KEY, name TEXT, department TEXT, bio TEXT, picture TEXT);
        CREATE TABLE IF NOT EXISTS media (id TEXT PRIMARY KEY, type TEXT, data ${db.postgres ? 'BYTEA' : 'BLOB'});
        CREATE TABLE IF NOT EXISTS posts (id TEXT PRIMARY KEY, owner TEXT, body TEXT, anonymous INTEGER, poll TEXT, media TEXT, created BIGINT);
        CREATE TABLE IF NOT EXISTS stories (id TEXT PRIMARY KEY, owner TEXT, media TEXT, created BIGINT);
        CREATE TABLE IF NOT EXISTS story_captions (id TEXT PRIMARY KEY, caption TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS reactions (post TEXT, owner TEXT, kind TEXT, value INTEGER, PRIMARY KEY(post, owner, kind));
        CREATE TABLE IF NOT EXISTS comments (id ${db.postgres ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : 'INTEGER'} PRIMARY KEY, post TEXT, owner TEXT, body TEXT, created BIGINT);
        CREATE TABLE IF NOT EXISTS memberships (owner TEXT, group_name TEXT, PRIMARY KEY(owner, group_name));
        CREATE TABLE IF NOT EXISTS messages (id ${db.postgres ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : 'INTEGER'} PRIMARY KEY, sender TEXT, recipient TEXT, body TEXT, created BIGINT);
        CREATE TABLE IF NOT EXISTS preferences (owner TEXT PRIMARY KEY, read_at BIGINT);
        CREATE TABLE IF NOT EXISTS activity_notifications (
            id TEXT PRIMARY KEY, recipient TEXT NOT NULL, actor TEXT NOT NULL,
            kind TEXT NOT NULL, target TEXT NOT NULL, created BIGINT NOT NULL
        );
        CREATE INDEX IF NOT EXISTS activity_recipient ON activity_notifications(recipient, created);
        CREATE TABLE IF NOT EXISTS reports (post TEXT, owner TEXT, created BIGINT, PRIMARY KEY(post, owner));
        CREATE TABLE IF NOT EXISTS people_preferences (
            owner TEXT NOT NULL, target TEXT NOT NULL, kind TEXT NOT NULL CHECK (kind IN ('mute', 'block')),
            PRIMARY KEY (owner, target, kind)
        );
        CREATE INDEX IF NOT EXISTS people_preferences_target ON people_preferences(target, kind, owner);
        CREATE TABLE IF NOT EXISTS friendships (
            first_id TEXT NOT NULL, second_id TEXT NOT NULL, requester TEXT NOT NULL, accepted INTEGER NOT NULL DEFAULT 0,
            PRIMARY KEY (first_id, second_id)
        );
        CREATE INDEX IF NOT EXISTS friendships_second ON friendships(second_id, first_id);
        CREATE TABLE IF NOT EXISTS follows (owner TEXT NOT NULL, target TEXT NOT NULL, PRIMARY KEY(owner, target));
        CREATE INDEX IF NOT EXISTS follows_target ON follows(target, owner);
        CREATE TABLE IF NOT EXISTS reposts (owner TEXT NOT NULL, post TEXT NOT NULL, created BIGINT NOT NULL, PRIMARY KEY(owner, post));
        CREATE TABLE IF NOT EXISTS story_reposts (owner TEXT NOT NULL, story TEXT NOT NULL, created BIGINT NOT NULL, PRIMARY KEY(owner, story));
        CREATE INDEX IF NOT EXISTS posts_created ON posts(created);
        CREATE INDEX IF NOT EXISTS stories_created ON stories(created);
        CREATE INDEX IF NOT EXISTS comments_post ON comments(post);
        CREATE INDEX IF NOT EXISTS messages_participants ON messages(sender, recipient, id);
    `);
    if (db.postgres) {
        await db.exec('ALTER TABLE profiles ADD COLUMN IF NOT EXISTS username TEXT');
    } else if (!db.prepare('PRAGMA table_info(profiles)').all().some(column => column.name === 'username')) {
        await db.exec('ALTER TABLE profiles ADD COLUMN username TEXT');
    }
    await db.exec('CREATE UNIQUE INDEX IF NOT EXISTS profiles_username ON profiles(username)');
    const profile = async id => (await db.prepare('SELECT name, department, bio, picture, username FROM profiles WHERE id = ?').get(id)) || {};
    const mediaUrl = id => id ? '/api/media/' + id : null;
    const viewProfile = async id => {
        const record = await profile(id);
        return { ...record, picture: mediaUrl(record.picture) };
    };
    const visibleAuthor = author => `NOT EXISTS (
        SELECT 1 FROM people_preferences pp
        WHERE (pp.owner = ? AND pp.target = ${author})
           OR (pp.target = ? AND pp.owner = ${author} AND pp.kind = 'block')
    )`;
    const noBlock = (author) => `NOT EXISTS (
        SELECT 1 FROM people_preferences pp WHERE pp.kind = 'block'
          AND ((pp.owner = ? AND pp.target = ${author}) OR (pp.target = ? AND pp.owner = ${author}))
    )`;
    const postById = (id, owner, lock = false) => db.prepare(`
        SELECT * FROM posts WHERE id = ? AND id NOT IN (SELECT id FROM hidden_posts) AND ${visibleAuthor('posts.owner')}
        ${lock && db.postgres ? 'FOR UPDATE' : ''}
    `).get(id, owner, owner);
    const blocked = (owner, peer) => db.prepare(`SELECT 1 FROM people_preferences WHERE kind = 'block'
        AND ((owner = ? AND target = ?) OR (owner = ? AND target = ?))`).get(owner, peer, peer, owner);
    const friendship = (owner, peer) => db.prepare('SELECT requester, accepted FROM friendships WHERE first_id = ? AND second_id = ?').get(...[owner, peer].sort());
    const withPair = (owner, peer, work) => db.transaction(async () => {
        if (db.postgres) {
            await db.prepare('SELECT id FROM accounts WHERE id IN (?, ?) ORDER BY id FOR UPDATE').all(owner, peer);
        }
        return work();
    });
    const currentStudent = async id => {
        const student = await db.prepare('SELECT email FROM accounts WHERE id = ? AND id NOT IN (SELECT id FROM disabled_accounts)').get(id);
        return student && approvedStudent(student.email);
    };
    async function messageAccess(owner, peer) {
        const sent = Boolean(await db.prepare('SELECT 1 FROM follows WHERE owner = ? AND target = ?').get(owner, peer));
        const received = Boolean(await db.prepare('SELECT 1 FROM follows WHERE owner = ? AND target = ?').get(peer, owner));
        const count = (await db.prepare('SELECT CAST(count(*) AS INTEGER) AS total FROM messages WHERE sender = ? AND recipient = ?').get(owner, peer)).total;
        return { followed: sent, followsYou: received, messagesRemaining: Math.max(0, 5 - count), canMessage: sent && (received || count < 5) };
    }
    async function notify(recipient, actor, kind, target, created) {
        if (recipient === actor) return;
        await db.prepare('INSERT INTO activity_notifications VALUES (?, ?, ?, ?, ?, ?)').run(randomUUID(), recipient, actor, kind, target, created);
    }

    async function upload(input, imageOnly = false) {
        if (!input || !mediaTypes.has(input.type) || (imageOnly && !input.type.startsWith('image/')) ||
            typeof input.data !== 'string' || input.data.length > 7_000_000 || !/^[A-Za-z0-9+/]+={0,2}$/.test(input.data)) return null;
        const data = Buffer.from(input.data, 'base64');
        if (data.length > 5_000_000 || !mediaSignatures[input.type](data)) return null;
        const id = randomUUID();
        await db.prepare('INSERT INTO media VALUES (?, ?, ?)').run(id, input.type, data);
        return id;
    }

    async function postView(row, owner) {
        const options = JSON.parse(row.poll);
        const summary = await db.prepare(`
            SELECT profiles.name AS author, media.type AS media_type,
                (SELECT CAST(count(*) AS INTEGER) FROM reactions WHERE post = posts.id AND kind = 'like') AS likes,
                (SELECT CAST(count(*) AS INTEGER) FROM comments WHERE post = posts.id) AS comments,
                EXISTS (SELECT 1 FROM reactions WHERE post = posts.id AND owner = ? AND kind = 'like') AS liked,
                EXISTS (SELECT 1 FROM reactions WHERE post = posts.id AND owner = ? AND kind = 'save') AS saved,
                (SELECT value FROM reactions WHERE post = posts.id AND owner = ? AND kind = 'vote') AS choice,
                (SELECT CAST(count(*) AS INTEGER) FROM reactions WHERE post = posts.id AND kind = 'vote' AND value = 0) AS first_votes,
                (SELECT CAST(count(*) AS INTEGER) FROM reactions WHERE post = posts.id AND kind = 'vote' AND value = 1) AS second_votes
            FROM posts LEFT JOIN profiles ON profiles.id = posts.owner LEFT JOIN media ON media.id = posts.media
            WHERE posts.id = ?
        `).get(owner, owner, owner, row.id);
        if (!summary) return null;
        const { author, media_type, likes, comments, liked, saved, choice, first_votes, second_votes } = summary;
        return {
            id: row.id, text: row.body, anonymous: Boolean(row.anonymous), own: row.owner === owner,
            authorId: row.anonymous ? null : row.owner,
            author: row.anonymous ? 'Anonymous Student' : author || 'Anchor student',
            created: Number(row.created), file: media_type ? { type: media_type, url: mediaUrl(row.media) } : null,
            poll: options ? { options, votes: [first_votes, second_votes], choice } : null,
            likes, comments, liked: Boolean(liked), saved: Boolean(saved),
            reposted: Boolean(await db.prepare('SELECT 1 FROM reposts WHERE owner = ? AND post = ?').get(owner, row.id))
        };
    }

    const postViews = async (rows, owner) => (await Promise.all(rows.map(row => postView(row, owner)))).filter(Boolean);

    return async function community(method, path, params, member, input) {
        const owner = member.id;
        const now = Date.now();
        if (method === 'GET') {
            if (path === '/api/profile') {
                const target = params.get('id') || owner;
                if (!await currentStudent(target) || await blocked(owner, target)) return missing;
                const record = await viewProfile(target);
                const stats = await db.prepare(`SELECT
                    (SELECT CAST(count(*) AS INTEGER) FROM follows WHERE target = ?) AS followers,
                    (SELECT CAST(count(*) AS INTEGER) FROM follows WHERE owner = ?) AS following,
                    EXISTS (SELECT 1 FROM follows WHERE owner = ? AND target = ?) AS followed`).get(target, target, owner, target);
                return { data: { ...record, ...stats, ...await messageAccess(owner, target), id: target, own: target === owner } };
            }
            if (path === '/api/profile-posts') {
                const target = params.get('id');
                if (!await currentStudent(target) || await blocked(owner, target)) return missing;
                const rows = await db.prepare(`SELECT * FROM posts WHERE owner = ? AND anonymous = 0
                    AND id NOT IN (SELECT id FROM hidden_posts) AND ${visibleAuthor('posts.owner')}
                    ORDER BY created DESC, id DESC LIMIT 100`).all(target, owner, owner);
                return { data: await postViews(rows, owner) };
            }
            if (path === '/api/post') {
                const post = await postById(params.get('id'), owner);
                const view = post && await postView(post, owner);
                return view ? { data: view } : missing;
            }
            if (path === '/api/my-posts') {
                const rows = await db.prepare('SELECT * FROM posts WHERE owner = ? AND anonymous = 0 AND id NOT IN (SELECT id FROM hidden_posts) ORDER BY created DESC, id DESC LIMIT 100').all(owner);
                return { data: await postViews(rows, owner) };
            }
            if (path === '/api/feed') {
                const rows = params.get('media') === 'video'
                    ? await db.prepare(`SELECT posts.* FROM posts JOIN media ON media.id = posts.media WHERE media.type LIKE 'video/%' AND posts.id NOT IN (SELECT id FROM hidden_posts) AND ${visibleAuthor('posts.owner')} ORDER BY posts.created DESC LIMIT 100`).all(owner, owner)
                    : await db.prepare(`SELECT * FROM posts WHERE id NOT IN (SELECT id FROM hidden_posts) AND ${visibleAuthor('posts.owner')} ORDER BY created DESC, id DESC LIMIT 100`).all(owner, owner);
                const shares = await db.prepare(`SELECT posts.*, reposts.created AS shared_at, profiles.name AS shared_by
                    FROM reposts JOIN posts ON posts.id = reposts.post LEFT JOIN profiles ON profiles.id = reposts.owner
                    WHERE posts.id NOT IN (SELECT id FROM hidden_posts)
                    AND ${visibleAuthor('posts.owner')} AND ${visibleAuthor('reposts.owner')}
                    ${params.get('media') === 'video' ? "AND EXISTS (SELECT 1 FROM media WHERE media.id = posts.media AND media.type LIKE 'video/%')" : ''}
                    ORDER BY reposts.created DESC LIMIT 100`).all(owner, owner, owner, owner);
                const reposted = await Promise.all(shares.map(async row => {
                    const view = await postView(row, owner);
                    return view && { ...view, repostedBy: row.shared_by || 'Anchor student', sharedAt: Number(row.shared_at) };
                }));
                return { data: [...await postViews(rows, owner), ...reposted.filter(Boolean)]
                    .sort((a, b) => (b.sharedAt || b.created) - (a.sharedAt || a.created)).slice(0, 100) };
            }
            if (path === '/api/saved') {
                const rows = await db.prepare(`SELECT posts.* FROM reactions JOIN posts ON posts.id = reactions.post WHERE reactions.owner = ? AND reactions.kind = 'save' AND posts.id NOT IN (SELECT id FROM hidden_posts) AND ${visibleAuthor('posts.owner')} ORDER BY posts.created DESC LIMIT 100`).all(owner, owner, owner);
                return { data: await postViews(rows, owner) };
            }
            if (path === '/api/stories') {
                const rows = await db.prepare(`SELECT stories.*, media.type, story_captions.caption FROM stories
                    JOIN media ON media.id = stories.media LEFT JOIN story_captions ON story_captions.id = stories.id
                    WHERE created > ? AND ${visibleAuthor('stories.owner')} ORDER BY created DESC LIMIT 100`).all(now - 86_400_000, owner, owner);
                const stories = await Promise.all(rows.map(async row => ({ id: row.id, type: row.type, url: mediaUrl(row.media), own: row.owner === owner,
                    caption: row.caption || '', author: (await profile(row.owner)).name || 'Anchor student' })));
                const shares = await db.prepare(`SELECT story_reposts.story, profiles.name, story_reposts.owner
                    FROM story_reposts LEFT JOIN profiles ON profiles.id = story_reposts.owner
                    WHERE ${visibleAuthor('story_reposts.owner')} ORDER BY story_reposts.created DESC LIMIT 100`).all(owner, owner);
                return { data: [...stories, ...shares.flatMap(share => {
                    const original = stories.find(story => story.id === share.story);
                    return original ? [{ ...original, own: false, repostedBy: share.name || 'Anchor student', repostOwn: share.owner === owner }] : [];
                })] };
            }
            if (path === '/api/memberships') return { data: (await db.prepare('SELECT group_name FROM memberships WHERE owner = ?').all(owner)).map(row => row.group_name) };
            if (path === '/api/students') {
                const nameQuery = (params.get('name') || '').trim();
                const contacts = params.get('contacts') === '1';
                if (!contacts && (nameQuery.length < 2 || nameQuery.length > 60)) return { data: [] };
                const filter = contacts
                    ? `(EXISTS (SELECT 1 FROM follows f WHERE (f.owner = ? AND f.target = accounts.id) OR (f.target = ? AND f.owner = accounts.id))
                        OR EXISTS (SELECT 1 FROM messages m WHERE (m.sender = ? AND m.recipient = accounts.id) OR (m.recipient = ? AND m.sender = accounts.id)))`
                    : "LOWER(profiles.name) LIKE ? ESCAPE '!'";
                const search = '%' + nameQuery.toLowerCase().replace(/[!%_]/g, '!$&') + '%';
                const rows = await db.prepare(`SELECT accounts.id, accounts.email, profiles.name, profiles.department, profiles.username
                    FROM accounts LEFT JOIN profiles USING (id) WHERE accounts.id != ? AND ${noBlock('accounts.id')}
                    AND accounts.id NOT IN (SELECT id FROM disabled_accounts) AND ${filter}
                    ORDER BY profiles.name, accounts.id LIMIT 50`).all(owner, owner, owner, ...(contacts ? [owner, owner, owner, owner] : [search]));
                return { data: await Promise.all(rows.filter(row => approvedStudent(row.email)).map(async ({ id, name, department, username }) =>
                    ({ id, name: name || 'Anchor student', department, username, ...await messageAccess(owner, id) }))) };
            }
            if (path === '/api/people-preferences') {
                return { data: await db.prepare(`SELECT pp.target AS id, pp.kind, profiles.name, profiles.username
                    FROM people_preferences pp LEFT JOIN profiles ON profiles.id = pp.target WHERE pp.owner = ?
                    ORDER BY pp.kind, profiles.name, pp.target`).all(owner) };
            }
            if (path === '/api/messages') {
                const peer = params.get('peer');
                if (peer !== 'campus-live' && (peer === owner || !await currentStudent(peer) || await blocked(owner, peer))) return missing;
                if (peer !== 'campus-live') {
                    const access = await messageAccess(owner, peer);
                    if (!access.followed && !access.followsYou) return missing;
                }
                const rows = peer === 'campus-live'
                    ? await db.prepare(`SELECT * FROM messages WHERE recipient = 'campus-live' AND ${noBlock('messages.sender')} ORDER BY id DESC LIMIT 100`).all(owner, owner)
                    : await db.prepare('SELECT * FROM messages WHERE (sender = ? AND recipient = ?) OR (sender = ? AND recipient = ?) ORDER BY id DESC LIMIT 100').all(owner, peer, peer, owner);
                return { data: await Promise.all(rows.reverse().map(async row => ({ id: row.id, own: row.sender === owner, author: (await profile(row.sender)).name || 'Anchor student', text: row.body }))) };
            }
            if (path === '/api/notifications') {
                const readAt = Number((await db.prepare('SELECT read_at FROM preferences WHERE owner = ?').get(owner))?.read_at ?? 0);
                const rows = await db.prepare(`SELECT id, sender, body, created FROM messages WHERE recipient = ?
                    AND ${noBlock('messages.sender')}
                    AND EXISTS (SELECT 1 FROM follows f WHERE
                        ((f.owner = messages.sender AND f.target = messages.recipient) OR
                         (f.target = messages.sender AND f.owner = messages.recipient)))
                    ORDER BY id DESC LIMIT 30`).all(owner, owner, owner);
                const activity = await db.prepare(`SELECT n.*, profiles.name FROM activity_notifications n
                    LEFT JOIN profiles ON profiles.id = n.actor WHERE n.recipient = ?
                    AND ${noBlock('n.actor')}
                    AND n.actor NOT IN (SELECT id FROM disabled_accounts)
                    AND (n.kind != 'repost' OR EXISTS (SELECT 1 FROM posts WHERE posts.id = n.target AND posts.id NOT IN (SELECT id FROM hidden_posts)))
                    ORDER BY n.created DESC, n.id DESC LIMIT 100`).all(owner, owner, owner);
                const items = activity.map(row => ({
                    id: row.id, kind: row.kind, author: row.name || 'Anchor student',
                    href: row.kind === 'follow' ? '/profile.html?id=' + encodeURIComponent(row.actor)
                        : row.kind === 'repost' ? '/?post=' + encodeURIComponent(row.target)
                        : '/?message=' + encodeURIComponent(row.actor),
                    created: Number(row.created), unread: Number(row.created) > readAt
                }));
                return { data: { read: readAt > 0, items, unreadCount: items.filter(item => item.unread).length,
                    messages: await Promise.all(rows.map(async row => ({ id: row.id, author: (await profile(row.sender)).name || 'Anchor student', text: row.body, unread: row.created > readAt }))) } };
            }
            if (path.startsWith('/api/media/')) {
                const id = path.slice('/api/media/'.length);
                const row = await db.prepare(`SELECT type, data FROM media WHERE id = ? AND (
                    EXISTS (SELECT 1 FROM posts WHERE posts.media = media.id AND posts.id NOT IN (SELECT id FROM hidden_posts) AND ${visibleAuthor('posts.owner')}) OR
                    EXISTS (SELECT 1 FROM profiles WHERE profiles.picture = media.id AND ${noBlock('profiles.id')}) OR
                    EXISTS (SELECT 1 FROM stories WHERE stories.media = media.id AND created > ? AND ${visibleAuthor('stories.owner')})
                )`).get(id, owner, owner, owner, owner, now - 86_400_000, owner, owner);
                return row ? { media: row } : missing;
            }
        }

        const parts = /^\/api\/posts\/([a-f0-9-]{36})\/(like|save|vote|comments|report|delete|edit|repost)$/.exec(path);
        if (parts) {
            const [, id, action] = parts;
            if (method === 'GET' && action === 'comments') {
                if (!await postById(id, owner)) return missing;
                const rows = await db.prepare(`SELECT owner, body FROM comments WHERE post = ? AND ${noBlock('comments.owner')} ORDER BY id DESC LIMIT 100`).all(id, owner, owner);
                return { data: await Promise.all(rows.reverse().map(async row => ({ text: row.body, author: (await profile(row.owner)).name || 'Anchor student' }))) };
            }
            if (method !== 'POST') return missing;
            if (action === 'delete') {
                return db.transaction(async () => {
                    const post = await db.prepare('SELECT owner, media FROM posts WHERE id = ?' + (db.postgres ? ' FOR UPDATE' : '')).get(id);
                    if (!post) return missing;
                    if (post.owner !== owner && !member.moderator) return { status: 403, error: 'Only the author or a moderator can delete this post.' };
                    await db.prepare('DELETE FROM posts WHERE id = ?').run(id);
                    await db.prepare('DELETE FROM comments WHERE post = ?').run(id);
                    await db.prepare('DELETE FROM reactions WHERE post = ?').run(id);
                    await db.prepare('DELETE FROM reports WHERE post = ?').run(id);
                    await db.prepare('DELETE FROM hidden_posts WHERE id = ?').run(id);
                    await db.prepare('DELETE FROM reposts WHERE post = ?').run(id);
                    if (post.media) await db.prepare('DELETE FROM media WHERE id = ?').run(post.media);
                    if (member.moderator) await db.prepare('INSERT INTO moderation_log(moderator, target, action, created) VALUES (?, ?, ?, ?)').run(owner, id, 'delete', now);
                    return { data: { ok: true } };
                });
            }
            return db.transaction(async () => {
                const post = await postById(id, owner, true);
                if (!post) return missing;
                if (action === 'repost') {
                    if (typeof input?.enabled !== 'boolean') return invalid;
                    if (input.enabled) {
                        const inserted = await db.prepare('INSERT INTO reposts VALUES (?, ?, ?) ON CONFLICT DO NOTHING').run(owner, id, now);
                        if (inserted.changes) await notify(post.owner, owner, 'repost', id, now);
                    }
                    else await db.prepare('DELETE FROM reposts WHERE owner = ? AND post = ?').run(owner, id);
                } else if (action === 'edit') {
                    if (post.owner !== owner) return { status: 403, error: 'Only the author can edit this post.' };
                    if (typeof input?.text !== 'string' || input.text.trim().length > 3000 || (!input.text.trim() && !post.media)) return invalid;
                    await db.prepare('UPDATE posts SET body = ? WHERE id = ?').run(input.text.trim(), id);
                    post.body = input.text.trim();
                } else if (action === 'comments') {
                    const body = text(input?.text, 1000);
                    if (!body) return invalid;
                    await db.prepare('INSERT INTO comments(post, owner, body, created) VALUES (?, ?, ?, ?)').run(id, owner, body, now);
                } else if (action === 'report') {
                    await db.prepare('INSERT INTO reports VALUES (?, ?, ?) ON CONFLICT DO NOTHING').run(id, owner, now);
                } else if (action === 'vote') {
                    const options = JSON.parse(post.poll);
                    const choice = input?.choice;
                    if (!options || !Number.isInteger(choice) || choice < 0 || choice >= options.length) return invalid;
                    await db.prepare("INSERT INTO reactions VALUES (?, ?, 'vote', ?) ON CONFLICT DO NOTHING").run(id, owner, choice);
                } else {
                    if (typeof input?.enabled !== 'boolean') return invalid;
                    if (input.enabled) await db.prepare('INSERT INTO reactions VALUES (?, ?, ?, 1) ON CONFLICT DO NOTHING').run(id, owner, action);
                    else await db.prepare('DELETE FROM reactions WHERE post = ? AND owner = ? AND kind = ?').run(id, owner, action);
                }
                return { data: await postView(post, owner) };
            });
        }

        if (method !== 'POST') return missing;
        if (path === '/api/people-preferences' || path === '/api/friendships' || path === '/api/follow') {
            const peer = typeof input?.peer === 'string' ? input.peer : '';
            if (peer === owner || !peer) return missing;
            const pair = [owner, peer].sort();
            return withPair(owner, peer, async () => {
                if (path === '/api/follow') {
                    if (typeof input.enabled !== 'boolean') return invalid;
                    if (!await currentStudent(peer) || await blocked(owner, peer)) return missing;
                    if (input.enabled) {
                        const inserted = await db.prepare('INSERT INTO follows VALUES (?, ?) ON CONFLICT DO NOTHING').run(owner, peer);
                        if (inserted.changes) await notify(peer, owner, 'follow', owner, now);
                    }
                    else await db.prepare('DELETE FROM follows WHERE owner = ? AND target = ?').run(owner, peer);
                    return { data: { followed: input.enabled } };
                }
                if (path === '/api/people-preferences') {
                    const { kind, enabled } = input;
                    if (!['mute', 'block'].includes(kind) || typeof enabled !== 'boolean') return invalid;
                    if (enabled) {
                        if (!await currentStudent(peer)) return missing;
                        await db.prepare('INSERT INTO people_preferences VALUES (?, ?, ?) ON CONFLICT DO NOTHING').run(owner, peer, kind);
                        if (kind === 'block') {
                            await db.prepare('DELETE FROM friendships WHERE first_id = ? AND second_id = ?').run(...pair);
                            await db.prepare('DELETE FROM follows WHERE (owner = ? AND target = ?) OR (owner = ? AND target = ?)').run(owner, peer, peer, owner);
                        }
                    } else {
                        await db.prepare('DELETE FROM people_preferences WHERE owner = ? AND target = ? AND kind = ?').run(owner, peer, kind);
                    }
                    return { data: { ok: true } };
                }
                if (!await currentStudent(peer) || await blocked(owner, peer)) return missing;
                const relation = await friendship(owner, peer);
                if (input.action === 'request') {
                    await db.prepare('INSERT INTO friendships (first_id, second_id, requester) VALUES (?, ?, ?) ON CONFLICT DO NOTHING').run(...pair, owner);
                } else if (['accept', 'decline'].includes(input.action) && relation && relation.requester === peer && !relation.accepted) {
                    if (input.action === 'accept') await db.prepare('UPDATE friendships SET accepted = 1 WHERE first_id = ? AND second_id = ?').run(...pair);
                    else await db.prepare('DELETE FROM friendships WHERE first_id = ? AND second_id = ?').run(...pair);
                } else if (input.action === 'cancel' && relation?.requester === owner && !relation.accepted) {
                    await db.prepare('DELETE FROM friendships WHERE first_id = ? AND second_id = ?').run(...pair);
                } else {
                    return invalid;
                }
                return { data: { ok: true } };
            });
        }
        if (path === '/api/profile') {
            const name = text(input?.name, 60);
            if (!name) return invalid;
            const existing = await profile(owner);
            const username = input.username === undefined ? existing.username || null : text(input.username, 24).toLowerCase();
            if (input.username !== undefined && !/^[a-z0-9_]{3,24}$/.test(username)) {
                return { status: 400, error: 'Use 3 to 24 letters, numbers, or underscores for your username.' };
            }
            if (username && await db.prepare('SELECT id FROM profiles WHERE username = ? AND id != ?').get(username, owner)) {
                return { status: 409, error: 'That username is taken. Choose another one.' };
            }
            const picture = input.file ? await upload(input.file, true) : existing.picture || null;
            if (input.file && !picture) return invalid;
            await db.prepare('INSERT INTO profiles (id, name, department, bio, picture, username) VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT(id) DO UPDATE SET name=excluded.name, department=excluded.department, bio=excluded.bio, picture=excluded.picture, username=excluded.username').run(owner, name, text(input.department, 100), text(input.bio, 250), picture, username);
            return { data: await viewProfile(owner) };
        }
        if (path === '/api/feed') {
            const body = text(input?.text, 3000);
            const options = input?.poll;
            if ((!body && !(input?.file && typeof input.text === 'string' && !input.text.trim())) || (options != null && (!Array.isArray(options) || options.length !== 2 ||
                options.some(option => !text(option, 160)) || text(options[0], 160) === text(options[1], 160) || input.file))) return invalid;
            const media = input.file ? await upload(input.file) : null;
            if (input.file && !media) return invalid;
            const id = randomUUID();
            await db.prepare('INSERT INTO posts VALUES (?, ?, ?, ?, ?, ?, ?)').run(id, owner, body, Number(input.anonymous === true), JSON.stringify(options?.map(value => value.trim()) ?? null), media, now);
            return { data: await postView(await postById(id, owner), owner) };
        }
        if (path === '/api/stories') {
            if (input?.action === 'repost') {
                if (typeof input.id !== 'string' || typeof input.enabled !== 'boolean') return invalid;
                return db.transaction(async () => {
                    const original = await db.prepare(`SELECT id FROM stories WHERE id = ? AND created > ? AND ${visibleAuthor('stories.owner')}
                        ${db.postgres ? 'FOR UPDATE' : ''}`).get(input.id, now - 86_400_000, owner, owner);
                    if (!original) return missing;
                    if (input.enabled) await db.prepare('INSERT INTO story_reposts VALUES (?, ?, ?) ON CONFLICT DO NOTHING').run(owner, input.id, now);
                    else await db.prepare('DELETE FROM story_reposts WHERE owner = ? AND story = ?').run(owner, input.id);
                    return { data: { ok: true } };
                });
            }
            if (input?.action === 'edit' || input?.action === 'delete') {
                if (typeof input.id !== 'string' || (input.action === 'edit' && (typeof input.caption !== 'string' || input.caption.trim().length > 250))) return invalid;
                return db.transaction(async () => {
                    const story = await db.prepare('SELECT media FROM stories WHERE id = ? AND owner = ? AND created > ?' + (db.postgres ? ' FOR UPDATE' : '')).get(input.id, owner, now - 86_400_000);
                    if (!story) return missing;
                    if (input.action === 'delete') {
                        await db.prepare('DELETE FROM stories WHERE id = ?').run(input.id);
                        await db.prepare('DELETE FROM story_captions WHERE id = ?').run(input.id);
                        await db.prepare('DELETE FROM story_reposts WHERE story = ?').run(input.id);
                        await db.prepare('DELETE FROM media WHERE id = ?').run(story.media);
                    } else {
                        await db.prepare('INSERT INTO story_captions VALUES (?, ?) ON CONFLICT(id) DO UPDATE SET caption=excluded.caption').run(input.id, input.caption.trim());
                    }
                    return { data: { ok: true } };
                });
            }
            if (input?.caption !== undefined && (typeof input.caption !== 'string' || input.caption.trim().length > 250)) return invalid;
            return db.transaction(async () => {
                const media = await upload(input?.file);
                if (!media) return invalid;
                const id = randomUUID();
                await db.prepare('INSERT INTO stories VALUES (?, ?, ?, ?)').run(id, owner, media, now);
                if (input.caption?.trim()) await db.prepare('INSERT INTO story_captions VALUES (?, ?)').run(id, input.caption.trim());
                return { data: { ok: true } };
            });
        }
        if (path === '/api/memberships') {
            if (!groups.has(input?.group) || typeof input.joined !== 'boolean') return invalid;
            if (input.joined) await db.prepare('INSERT INTO memberships VALUES (?, ?) ON CONFLICT DO NOTHING').run(owner, input.group);
            else await db.prepare('DELETE FROM memberships WHERE owner = ? AND group_name = ?').run(owner, input.group);
            return { data: { joined: input.joined } };
        }
        if (path === '/api/messages') {
            const peer = typeof input?.peer === 'string' ? input.peer : '';
            const body = text(input?.text, 2000);
            if (!body || peer === owner || (peer !== 'campus-live' && !await currentStudent(peer))) return invalid;
            const sendMessage = async () => {
                if (peer !== 'campus-live' && (!await currentStudent(peer) || await blocked(owner, peer))) return missing;
                if (peer !== 'campus-live' && !(await messageAccess(owner, peer)).canMessage) {
                    return { status: 403, error: 'Follow this person to send a request. After five messages, wait for them to follow you back.' };
                }
                await db.prepare('INSERT INTO messages(sender, recipient, body, created) VALUES (?, ?, ?, ?)').run(owner, peer, body, now);
                if (peer !== 'campus-live') {
                    const access = await messageAccess(owner, peer);
                    if (access.followsYou) await notify(peer, owner, 'message', owner, now);
                    else if (access.messagesRemaining === 4) await notify(peer, owner, 'message-request', owner, now);
                }
                return { data: { ok: true } };
            };
            return peer === 'campus-live' ? sendMessage() : withPair(owner, peer, sendMessage);
        }
        if (path === '/api/notifications') {
            await db.prepare('INSERT INTO preferences VALUES (?, ?) ON CONFLICT(owner) DO UPDATE SET read_at=excluded.read_at').run(owner, now);
            return { data: { ok: true } };
        }
        return missing;
    };
}
