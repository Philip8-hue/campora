import { randomUUID } from 'node:crypto';

const groups = new Set(['NACOS', 'Press Club', 'Law Society', 'GDSC']);
const mediaTypes = new Set(['image/jpeg', 'image/png', 'image/gif', 'image/webp', 'video/mp4', 'video/webm']);
const mediaSignatures = {
    'image/jpeg': data => data.subarray(0, 3).toString('hex') === 'ffd8ff',
    'image/png': data => data.subarray(0, 8).toString('hex') === '89504e470d0a1a0a',
    'image/gif': data => ['GIF87a', 'GIF89a'].includes(data.toString('ascii', 0, 6)),
    'image/webp': data => data.toString('ascii', 0, 4) === 'RIFF' && data.toString('ascii', 8, 12) === 'WEBP',
    'video/mp4': data => data.toString('ascii', 4, 8) === 'ftyp',
    'video/webm': data => data.subarray(0, 4).toString('hex') === '1a45dfa3'
};
const text = (value, max) => typeof value === 'string' && value.trim().length <= max ? value.trim() : '';
const invalid = { status: 400, error: 'Check the information and try again.' };
const missing = { status: 404, error: 'This item is unavailable.' };

export async function createCommunity(db, approvedStudent) {
    await db.exec(`
        CREATE TABLE IF NOT EXISTS profiles (id TEXT PRIMARY KEY, name TEXT, department TEXT, bio TEXT, picture TEXT);
        CREATE TABLE IF NOT EXISTS media (id TEXT PRIMARY KEY, type TEXT, data ${db.postgres ? 'BYTEA' : 'BLOB'});
        CREATE TABLE IF NOT EXISTS posts (id TEXT PRIMARY KEY, owner TEXT, body TEXT, anonymous INTEGER, poll TEXT, media TEXT, created BIGINT);
        CREATE TABLE IF NOT EXISTS stories (id TEXT PRIMARY KEY, owner TEXT, media TEXT, created BIGINT);
        CREATE TABLE IF NOT EXISTS reactions (post TEXT, owner TEXT, kind TEXT, value INTEGER, PRIMARY KEY(post, owner, kind));
        CREATE TABLE IF NOT EXISTS comments (id ${db.postgres ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : 'INTEGER'} PRIMARY KEY, post TEXT, owner TEXT, body TEXT, created BIGINT);
        CREATE TABLE IF NOT EXISTS memberships (owner TEXT, group_name TEXT, PRIMARY KEY(owner, group_name));
        CREATE TABLE IF NOT EXISTS messages (id ${db.postgres ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : 'INTEGER'} PRIMARY KEY, sender TEXT, recipient TEXT, body TEXT, created BIGINT);
        CREATE TABLE IF NOT EXISTS preferences (owner TEXT PRIMARY KEY, read_at BIGINT);
        CREATE TABLE IF NOT EXISTS reports (post TEXT, owner TEXT, created BIGINT, PRIMARY KEY(post, owner));
        CREATE INDEX IF NOT EXISTS posts_created ON posts(created);
        CREATE INDEX IF NOT EXISTS stories_created ON stories(created);
        CREATE INDEX IF NOT EXISTS comments_post ON comments(post);
        CREATE INDEX IF NOT EXISTS messages_participants ON messages(sender, recipient, id);
    `);
    if (db.postgres) {
        await db.exec('ALTER TABLE profiles ADD COLUMN IF NOT EXISTS username TEXT');
    } else if (!db.prepare('PRAGMA table_info(profiles)').all().some(column => column.name === 'username')) {
        await db.exec('ALTER TABLE profiles ADD COLUMN username TEXT');
    }
    await db.exec('CREATE UNIQUE INDEX IF NOT EXISTS profiles_username ON profiles(username)');
    const profile = async id => (await db.prepare('SELECT name, department, bio, picture, username FROM profiles WHERE id = ?').get(id)) || {};
    const mediaUrl = id => id ? '/api/media/' + id : null;
    const viewProfile = async id => {
        const record = await profile(id);
        return { ...record, picture: mediaUrl(record.picture) };
    };
    const postById = async id => await db.prepare('SELECT * FROM posts WHERE id = ? AND id NOT IN (SELECT id FROM hidden_posts)').get(id);
    const currentStudent = async id => {
        const student = await db.prepare('SELECT email FROM accounts WHERE id = ?').get(id);
        return student && approvedStudent(student.email);
    };

    async function upload(input, imageOnly = false) {
        if (!input || !mediaTypes.has(input.type) || (imageOnly && !input.type.startsWith('image/')) ||
            typeof input.data !== 'string' || input.data.length > 7_000_000 || !/^[A-Za-z0-9+/]+={0,2}$/.test(input.data)) return null;
        const data = Buffer.from(input.data, 'base64');
        if (data.length > 5_000_000 || !mediaSignatures[input.type](data)) return null;
        const id = randomUUID();
        await db.prepare('INSERT INTO media VALUES (?, ?, ?)').run(id, input.type, data);
        return id;
    }

    async function postView(row, owner) {
        const options = JSON.parse(row.poll);
        const { author, media_type, likes, comments, liked, saved, choice, first_votes, second_votes } = await db.prepare(`
            SELECT profiles.name AS author, media.type AS media_type,
                (SELECT CAST(count(*) AS INTEGER) FROM reactions WHERE post = posts.id AND kind = 'like') AS likes,
                (SELECT CAST(count(*) AS INTEGER) FROM comments WHERE post = posts.id) AS comments,
                EXISTS (SELECT 1 FROM reactions WHERE post = posts.id AND owner = ? AND kind = 'like') AS liked,
                EXISTS (SELECT 1 FROM reactions WHERE post = posts.id AND owner = ? AND kind = 'save') AS saved,
                (SELECT value FROM reactions WHERE post = posts.id AND owner = ? AND kind = 'vote') AS choice,
                (SELECT CAST(count(*) AS INTEGER) FROM reactions WHERE post = posts.id AND kind = 'vote' AND value = 0) AS first_votes,
                (SELECT CAST(count(*) AS INTEGER) FROM reactions WHERE post = posts.id AND kind = 'vote' AND value = 1) AS second_votes
            FROM posts LEFT JOIN profiles ON profiles.id = posts.owner LEFT JOIN media ON media.id = posts.media
            WHERE posts.id = ?
        `).get(owner, owner, owner, row.id);
        return {
            id: row.id, text: row.body, anonymous: Boolean(row.anonymous), own: row.owner === owner,
            author: row.anonymous ? 'Anonymous Student' : author || 'Anchor student',
            created: Number(row.created), file: media_type ? { type: media_type, url: mediaUrl(row.media) } : null,
            poll: options ? { options, votes: [first_votes, second_votes], choice } : null,
            likes, comments, liked: Boolean(liked), saved: Boolean(saved)
        };
    }

    return async function community(method, path, params, member, input) {
        const owner = member.id;
        const now = Date.now();
        if (method === 'GET') {
            if (path === '/api/profile') return { data: await viewProfile(owner) };
            if (path === '/api/post') {
                const post = await postById(params.get('id'));
                return post ? { data: await postView(post, owner) } : missing;
            }
            if (path === '/api/my-posts') {
                const rows = await db.prepare('SELECT * FROM posts WHERE owner = ? AND anonymous = 0 AND id NOT IN (SELECT id FROM hidden_posts) ORDER BY created DESC, id DESC LIMIT 100').all(owner);
                return { data: await Promise.all(rows.map(row => postView(row, owner))) };
            }
            if (path === '/api/feed') {
                const rows = params.get('media') === 'video'
                    ? await db.prepare("SELECT posts.* FROM posts JOIN media ON media.id = posts.media WHERE media.type LIKE 'video/%' AND posts.id NOT IN (SELECT id FROM hidden_posts) ORDER BY posts.created DESC LIMIT 100").all()
                    : await db.prepare('SELECT * FROM posts WHERE id NOT IN (SELECT id FROM hidden_posts) ORDER BY created DESC, id DESC LIMIT 100').all();
                return { data: await Promise.all(rows.map(row => postView(row, owner))) };
            }
            if (path === '/api/saved') {
                const rows = await db.prepare("SELECT posts.* FROM reactions JOIN posts ON posts.id = reactions.post WHERE reactions.owner = ? AND kind = 'save' AND posts.id NOT IN (SELECT id FROM hidden_posts) ORDER BY posts.created DESC LIMIT 100").all(owner);
                return { data: await Promise.all(rows.map(row => postView(row, owner))) };
            }
            if (path === '/api/stories') {
                const rows = await db.prepare('SELECT stories.*, media.type FROM stories JOIN media ON media.id = stories.media WHERE created > ? ORDER BY created DESC LIMIT 100').all(now - 86_400_000);
                return { data: await Promise.all(rows.map(async row => ({ id: row.id, type: row.type, url: mediaUrl(row.media), author: (await profile(row.owner)).name || 'Anchor student' }))) };
            }
            if (path === '/api/memberships') return { data: (await db.prepare('SELECT group_name FROM memberships WHERE owner = ?').all(owner)).map(row => row.group_name) };
            if (path === '/api/students') {
                const rows = await db.prepare('SELECT accounts.id, accounts.email, profiles.name, profiles.department, profiles.username FROM accounts LEFT JOIN profiles USING (id) WHERE accounts.id != ? ORDER BY profiles.name, accounts.id').all(owner);
                return { data: rows.filter(row => approvedStudent(row.email)).map(({ id, name, department, username }) => ({ id, name: name || 'Anchor student', department, username })) };
            }
            if (path === '/api/messages') {
                const peer = params.get('peer');
                if (peer !== 'campus-live' && (peer === owner || !await currentStudent(peer))) return missing;
                const rows = peer === 'campus-live'
                    ? await db.prepare("SELECT * FROM messages WHERE recipient = 'campus-live' ORDER BY id DESC LIMIT 100").all()
                    : await db.prepare('SELECT * FROM messages WHERE (sender = ? AND recipient = ?) OR (sender = ? AND recipient = ?) ORDER BY id DESC LIMIT 100').all(owner, peer, peer, owner);
                return { data: await Promise.all(rows.reverse().map(async row => ({ id: row.id, own: row.sender === owner, author: (await profile(row.sender)).name || 'Anchor student', text: row.body }))) };
            }
            if (path === '/api/notifications') {
                const readAt = Number((await db.prepare('SELECT read_at FROM preferences WHERE owner = ?').get(owner))?.read_at ?? 0);
                const rows = await db.prepare('SELECT id, sender, body, created FROM messages WHERE recipient = ? ORDER BY id DESC LIMIT 30').all(owner);
                return { data: { read: readAt > 0, messages: await Promise.all(rows.map(async row => ({ id: row.id, author: (await profile(row.sender)).name || 'Anchor student', text: row.body, unread: row.created > readAt }))) } };
            }
            if (path.startsWith('/api/media/')) {
                const id = path.slice('/api/media/'.length);
                const row = await db.prepare(`SELECT type, data FROM media WHERE id = ? AND (
                    EXISTS (SELECT 1 FROM posts WHERE posts.media = media.id AND posts.id NOT IN (SELECT id FROM hidden_posts)) OR
                    EXISTS (SELECT 1 FROM profiles WHERE profiles.picture = media.id) OR
                    EXISTS (SELECT 1 FROM stories WHERE stories.media = media.id AND created > ?)
                )`).get(id, now - 86_400_000);
                return row ? { media: row } : missing;
            }
        }

        const parts = /^\/api\/posts\/([a-f0-9-]{36})\/(like|save|vote|comments|report)$/.exec(path);
        if (parts) {
            const [, id, action] = parts;
            const post = await postById(id);
            if (!post) return missing;
            if (method === 'GET' && action === 'comments') {
                const rows = await db.prepare('SELECT owner, body FROM comments WHERE post = ? ORDER BY id DESC LIMIT 100').all(id);
                return { data: await Promise.all(rows.reverse().map(async row => ({ text: row.body, author: (await profile(row.owner)).name || 'Anchor student' }))) };
            }
            if (method !== 'POST') return missing;
            if (action === 'comments') {
                const body = text(input?.text, 1000);
                if (!body) return invalid;
                await db.prepare('INSERT INTO comments(post, owner, body, created) VALUES (?, ?, ?, ?)').run(id, owner, body, now);
            } else if (action === 'report') {
                await db.prepare('INSERT INTO reports VALUES (?, ?, ?) ON CONFLICT DO NOTHING').run(id, owner, now);
            } else if (action === 'vote') {
                const options = JSON.parse(post.poll);
                const choice = input?.choice;
                if (!options || !Number.isInteger(choice) || choice < 0 || choice >= options.length) return invalid;
                await db.prepare("INSERT INTO reactions VALUES (?, ?, 'vote', ?) ON CONFLICT DO NOTHING").run(id, owner, choice);
            } else {
                if (typeof input?.enabled !== 'boolean') return invalid;
                if (input.enabled) await db.prepare('INSERT INTO reactions VALUES (?, ?, ?, 1) ON CONFLICT DO NOTHING').run(id, owner, action);
                else await db.prepare('DELETE FROM reactions WHERE post = ? AND owner = ? AND kind = ?').run(id, owner, action);
            }
            return { data: await postView(post, owner) };
        }

        if (method !== 'POST') return missing;
        if (path === '/api/profile') {
            const name = text(input?.name, 60);
            if (!name) return invalid;
            const existing = await profile(owner);
            const username = input.username === undefined ? existing.username || null : text(input.username, 24).toLowerCase();
            if (input.username !== undefined && !/^[a-z0-9_]{3,24}$/.test(username)) {
                return { status: 400, error: 'Use 3 to 24 letters, numbers, or underscores for your username.' };
            }
            if (username && await db.prepare('SELECT id FROM profiles WHERE username = ? AND id != ?').get(username, owner)) {
                return { status: 409, error: 'That username is taken. Choose another one.' };
            }
            const picture = input.file ? await upload(input.file, true) : existing.picture || null;
            if (input.file && !picture) return invalid;
            await db.prepare('INSERT INTO profiles (id, name, department, bio, picture, username) VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT(id) DO UPDATE SET name=excluded.name, department=excluded.department, bio=excluded.bio, picture=excluded.picture, username=excluded.username').run(owner, name, text(input.department, 100), text(input.bio, 250), picture, username);
            return { data: await viewProfile(owner) };
        }
        if (path === '/api/feed') {
            const body = text(input?.text, 3000);
            const options = input?.poll;
            if ((!body && !(input?.file && typeof input.text === 'string' && !input.text.trim())) || (options != null && (!Array.isArray(options) || options.length !== 2 ||
                options.some(option => !text(option, 160)) || text(options[0], 160) === text(options[1], 160) || input.file))) return invalid;
            const media = input.file ? await upload(input.file) : null;
            if (input.file && !media) return invalid;
            const id = randomUUID();
            await db.prepare('INSERT INTO posts VALUES (?, ?, ?, ?, ?, ?, ?)').run(id, owner, body, Number(input.anonymous === true), JSON.stringify(options?.map(value => value.trim()) ?? null), media, now);
            return { data: await postView(await postById(id), owner) };
        }
        if (path === '/api/stories') {
            const media = await upload(input?.file);
            if (!media) return invalid;
            await db.prepare('INSERT INTO stories VALUES (?, ?, ?, ?)').run(randomUUID(), owner, media, now);
            return { data: { ok: true } };
        }
        if (path === '/api/memberships') {
            if (!groups.has(input?.group) || typeof input.joined !== 'boolean') return invalid;
            if (input.joined) await db.prepare('INSERT INTO memberships VALUES (?, ?) ON CONFLICT DO NOTHING').run(owner, input.group);
            else await db.prepare('DELETE FROM memberships WHERE owner = ? AND group_name = ?').run(owner, input.group);
            return { data: { joined: input.joined } };
        }
        if (path === '/api/messages') {
            const peer = typeof input?.peer === 'string' ? input.peer : '';
            const body = text(input?.text, 2000);
            if (!body || peer === owner || (peer !== 'campus-live' && !await currentStudent(peer))) return invalid;
            await db.prepare('INSERT INTO messages(sender, recipient, body, created) VALUES (?, ?, ?, ?)').run(owner, peer, body, now);
            return { data: { ok: true } };
        }
        if (path === '/api/notifications') {
            await db.prepare('INSERT INTO preferences VALUES (?, ?) ON CONFLICT(owner) DO UPDATE SET read_at=excluded.read_at').run(owner, now);
            return { data: { ok: true } };
        }
        return missing;
    };
}
